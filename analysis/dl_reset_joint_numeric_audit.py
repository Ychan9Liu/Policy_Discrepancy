"""Independent, pure CPU numeric audit for newly generated reset joint bundles.

The caller authenticates the producer/complete/exit chain and supplies trusted
hash-pinned new readouts and numeric bundles. This module does not open source,
blind artifacts, files, models, or simulators, and imports no producer oracle.
Direct kernel solves independently recover all shared heads and LOEO choices.
Physical correctness and the actual full Agent.train mechanism need separate
audits; numbers matching here cannot establish those or method effectiveness.
"""
import hashlib
import json
import math
import pickle

import numpy as np


VERSION = 'DL-reset-joint-independent-numeric-audit-r1'
LAMBDAS = (1., .1, .01, .001)
CAL = (9, 14, 15, 18, 20, 24, 30, 31)
SIGNALS = ('D-only', 'D+K', 'D+S', 'S-only')
TOL = 1e-10
TIE = 1e-10
DELTA = .2
SEED = 20261026


def require(condition, message):
  if not condition:
    raise ValueError(message)


def digest(value):
  value = np.ascontiguousarray(value)
  require(not value.dtype.hasobject, 'Object-array digest forbidden')
  return dict(dtype=value.dtype.str, shape=list(value.shape),
              sha256=hashlib.sha256(value.tobytes()).hexdigest())


def load_hash_pinned_new_payload(payload, expected_sha256):
  """Only caller-supplied NEW project-generated bytes; never path/source loading."""
  require(type(payload) is bytes and isinstance(expected_sha256, str) and
          len(expected_sha256) == 64 and
          all(c in '0123456789abcdef' for c in expected_sha256), 'Payload/hash contract')
  require(hashlib.sha256(payload).hexdigest() == expected_sha256,
          'Hash mismatch before decoding new trusted payload')
  return pickle.loads(payload)


class Comparison:
  def __init__(self):
    self.numeric = 0
    self.exact = 0
    self.zero_sides = 0
    self.maximum = 0.

  def close(self, actual, expected, path):
    a, e = np.asarray(actual, np.float64), np.asarray(expected, np.float64)
    require(a.shape == e.shape and np.isfinite(a).all() and np.isfinite(e).all(),
            path + ': nonfinite/shape mismatch')
    error = float(np.max(np.abs(a - e))) if a.size else 0.
    self.maximum = max(self.maximum, error)
    self.numeric += a.size
    require(error <= TOL, path + ': numeric difference ' + repr(error))

  def same(self, actual, expected, path):
    self.exact += 1
    if isinstance(expected, np.ndarray):
      equal = np.array_equal(np.asarray(actual), expected)
    else:
      equal = actual == expected
    require(bool(equal), path + ': exact mismatch')

  def sides(self, actual, expected, path):
    a, e = np.asarray(actual, np.float64), np.asarray(expected, np.float64)
    require(a.shape == e.shape, path + ': zero-side shape')
    self.zero_sides += a.size
    require(np.array_equal(np.sign(a), np.sign(e)), path + ': zero-side mismatch')


def validate_batch(batch, n, name):
  require(isinstance(batch, dict) and set(batch) ==
          {'episode_ids', 'h', 'zq', 'zp', 'returns', 'D', 'K'}, name + ': keys')
  ids = batch['episode_ids']
  require(isinstance(ids, np.ndarray) and ids.dtype.kind in 'iu' and ids.shape == (n,) and
          len(np.unique(ids)) == n and np.all(ids >= 0), name + ': episodes')
  h = batch['h']
  require(isinstance(h, np.ndarray) and h.ndim == 2 and h.shape[0] == n and
          h.shape[1] > 0, name + ': h shape')
  for key, shape in (('h', h.shape), ('zq', (n, 4, 32, 32)),
      ('zp', (n, 4, 32, 32)), ('returns', (n, 7)), ('D', (n,)), ('K', (n,))):
    value = batch[key]
    require(isinstance(value, np.ndarray) and value.dtype == np.float64 and
            value.shape == shape and np.isfinite(value).all(), name + ': ' + key)
  require(np.all(batch['D'] >= 0.) and np.all(batch['K'] >= -1e-5), name + ': D/K guard')
  for key in ('zq', 'zp'):
    value = batch[key]
    require(np.all((value == 0.) | (value == 1.)) and np.all(value.sum(-1) == 1.),
            name + ': exact onehot')
  if n == 8:
    require(set(ids.tolist()) == set(CAL), name + ': cal set')


def mean(values):
  flat = np.asarray(values, np.float64).reshape(-1)
  require(len(flat) > 0 and np.isfinite(flat).all(), 'Finite nonempty mean required')
  return math.fsum(float(v) for v in flat) / len(flat)


def center(returns):
  difference = returns - returns[:, :1]
  # The exact declared mean rounding is part of fitting, not a choice tolerance.
  return difference - difference.mean(axis=1, keepdims=True, dtype=np.float64)


def normalized(values):
  mu = values.mean(axis=0, dtype=np.float64)
  c = values - mu
  rms = float(np.sqrt(np.square(c).sum(1).mean(dtype=np.float64)))
  require(np.isfinite(rms), 'Nonfinite normalization')
  if rms == 0.:
    require(np.all(c == 0.), 'Group RMS underflow')
    return np.zeros_like(values), mu, rms
  return c / rms, mu, rms


def direct_shared(cal, rows, rule):
  """Solve at most a 64x64 kernel; no producer code or eigensystem solver."""
  h = np.repeat(cal['h'][rows], 8, axis=0)
  z = np.concatenate((cal['zq'][rows], cal['zp'][rows]), axis=1).reshape((-1, 1024))
  y = np.repeat(center(cal['returns'][rows]), 8, axis=0)
  ht, hm, hr = normalized(h)
  zt, zm, zr = normalized(z)
  x = np.column_stack((ht, zt))
  n = len(x)
  bias = y.mean(axis=0, dtype=np.float64)
  kernel = x @ x.T / n
  system = kernel + rule * np.eye(n)
  dual = np.linalg.solve(system, y - bias)
  weights = x.T @ dual / n
  fitted = x @ weights + bias
  residual = fitted - y
  return dict(h_mean=hm, z_mean=zm, h_rms=hr, z_rms=zr, weights=weights,
      intercept=bias, lambda_value=rule, training_episodes=cal['episode_ids'][rows].tolist(),
      training_rows=n, targets_digest=digest(y),
      effective_df=float(np.trace(np.linalg.solve(system, kernel))),
      training_mse=mean(np.square(residual)), weight_norm=math.fsum(
          float(v) ** 2 for v in weights.reshape(-1)),
      equation_error=float(np.max(np.abs(system @ dual - (y - bias)))))


def predict(model, batch):
  n = len(batch['episode_ids'])
  hd = len(model['h_mean'])
  h = np.repeat(batch['h'], 8, axis=0)
  z = np.concatenate((batch['zq'], batch['zp']), axis=1).reshape((-1, 1024))
  ht = ((h - model['h_mean']) / model['h_rms']) if model['h_rms'] else np.zeros_like(h)
  zt = ((z - model['z_mean']) / model['z_rms']) if model['z_rms'] else np.zeros_like(z)
  require(h.shape[1] == hd, 'Direct model dimensions')
  samples = (np.column_stack((ht, zt)) @ model['weights'] + model['intercept']).reshape((n, 2, 4, 7))
  return samples.mean(axis=2, dtype=np.float64), samples


def decisions(prediction, returns):
  choice = np.argmax(prediction, axis=-1).astype(np.int32)
  q, p = choice[:, 0], choice[:, 1]
  rq = np.array([returns[i, q[i]] for i in range(len(q))], np.float64)
  rp = np.array([returns[i, p[i]] for i in range(len(p))], np.float64)
  S = np.array([prediction[i, 0, q[i]] - prediction[i, 0, p[i]]
                for i in range(len(q))], np.float64)
  require(np.all(S >= 0.), 'Direct S identity failed')
  return dict(choices=choice, S=S, U=rq - rp, q=rq, p=rp)


def verify_fit(stored, computed, compare, path):
  for key in ('h_mean', 'z_mean', 'h_rms', 'z_rms', 'weights', 'intercept'):
    compare.close(stored[key], computed[key], path + '.' + key)
  compare.same(stored['lambda_value'], computed['lambda_value'], path + '.lambda')
  meta = stored['metadata']
  for key in ('training_episodes', 'training_rows'):
    compare.same(meta[key], computed[key], path + '.' + key)
  for key, expected in (('parameters_shared', True), ('branch_id_input', False),
      ('intercept_regularized', False), ('all_eigenvalues_retained', True),
      ('action_centered_targets', True)):
    compare.same(meta[key], expected, path + '.' + key)
  compare.same(meta['targets'], computed['targets_digest'], path + '.targets_digest')
  compare.same(meta['h_mean'], digest(computed['h_mean']), path + '.h_mean_digest')
  compare.same(meta['z_mean'], digest(computed['z_mean']), path + '.z_mean_digest')
  compare.close(meta['effective_df'], computed['effective_df'], path + '.effective_df')
  compare.close(meta['training_mse_per_control'], computed['training_mse'], path + '.training_mse')
  compare.close(meta['squared_weight_norm'], computed['weight_norm'], path + '.weight_norm')
  compare.close(meta['regularized_objective'],
      computed['training_mse'] * 7 + computed['lambda_value'] * computed['weight_norm'],
      path + '.regularized_objective')
  require(computed['equation_error'] <= TOL, path + ': direct equation residual')


def verify_fold_metadata(stored, computed, compare, path):
  # Fold producer stores metadata but not a second full high-dimensional W.
  for key in ('training_episodes', 'training_rows'):
    compare.same(stored[key], computed[key], path + '.' + key)
  compare.same(stored['targets'], computed['targets_digest'], path + '.targets')
  compare.same(stored['h_mean'], digest(computed['h_mean']), path + '.h_mean')
  compare.same(stored['z_mean'], digest(computed['z_mean']), path + '.z_mean')
  compare.close(stored['effective_df'], computed['effective_df'], path + '.effective_df')
  compare.close(stored['training_mse_per_control'], computed['training_mse'], path + '.mse')
  compare.close(stored['squared_weight_norm'], computed['weight_norm'], path + '.norm')


def select_lambda(candidates):
  largest = max(row['pooled_utility'] for row in candidates)
  first = [row for row in candidates if row['pooled_utility'] >= largest - TIE]
  smallest = min(row['pooled_mse'] for row in first)
  second = [row for row in first if row['pooled_mse'] <= smallest + TIE]
  return max(row['lambda'] for row in second), sorted(
      (row['lambda'] for row in first), reverse=True), sorted(
      (row['lambda'] for row in second), reverse=True)


def slot_values(name, D, K, S):
  zero = np.zeros_like(D)
  if name == 'D-only': return np.column_stack((D, zero))
  if name == 'D+K': return np.column_stack((D, K))
  if name == 'D+S': return np.column_stack((D, S))
  if name == 'S-only': return np.column_stack((S, zero))
  raise ValueError('Unknown signal name')


def direct_signal(slots, target):
  mu = slots.mean(axis=0, dtype=np.float64)
  difference = slots - mu
  rms = np.sqrt(np.square(difference).mean(axis=0, dtype=np.float64))
  active = rms > 0.
  x = np.zeros_like(slots)
  x[:, active] = difference[:, active] / rms[active]
  bias = float(target.mean(dtype=np.float64))
  gram = x.T @ x / len(x)
  weights = np.linalg.solve(gram + np.eye(2), x.T @ (target - bias) / len(x))
  return dict(mean=mu, rms=rms, weights=weights, intercept=bias,
      effective_df=float(np.trace(np.linalg.solve(gram + np.eye(2), gram))),
      rank=int(np.linalg.matrix_rank(x)), training_predictions=x @ weights + bias,
      constant_target=bool(np.all(target == target[0])))


def signal_predict(model, slots):
  active = model['rms'] > 0.
  x = np.zeros_like(slots)
  x[:, active] = (slots[:, active] - model['mean'][active]) / model['rms'][active]
  return x @ model['weights'] + model['intercept']


def summary(values, indices):
  values = np.asarray(values, np.float64)
  require(values.shape == (24,), 'Exactly 24 episode units required')
  draws = np.array([math.fsum(float(values[i]) for i in row) / 24 for row in indices])
  return dict(values=values, mean=mean(values),
              ci95=np.percentile(draws, [2.5, 97.5], method='linear'))


def verify_summary(stored, expected, compare, path):
  for key in ('values', 'mean', 'ci95'):
    compare.close(stored[key], expected[key], path + '.' + key)
  compare.sides(stored['ci95'], expected['ci95'], path + '.ci95')
  compare.same(stored['bootstrap_unit'], 'whole episode', path + '.unit')
  compare.same(stored['bootstrap_draws'], 2000, path + '.draws')


def coverage(decision, D, threshold):
  high = D >= threshold
  positive, nonpositive = decision['U'] >= DELTA, decision['U'] <= 0.
  disagree = decision['choices'][:, 0] != decision['choices'][:, 1]
  wrong = disagree & (decision['U'] < 0.)
  out = {}
  for name, mask in (('all', np.ones(24, bool)), ('high_D', high)):
    pos, nonpos, neg = [int(np.sum(mask & x)) for x in (positive, nonpositive, wrong)]
    out[name] = dict(total=int(mask.sum()), practical_positive=pos, nonpositive=nonpos,
        wrong_choice_negative=neg, identity_nonpositive=int(np.sum(mask & nonpositive & ~disagree)),
        minimum_coverage_met=bool(pos >= 4 and nonpos >= 4 and neg >= 2))
  out['high_D_threshold'] = threshold
  return out


def audit_numeric(readouts, blind, result):
  """Independently verify all frozen fits and once-held-out numerical outputs."""
  require(isinstance(readouts, dict) and set(readouts) == {'frozen', 'refits', 'cal'},
          'New readouts schema differs')
  require(set(readouts['cal']) == {'0', 'B', 'R'} and set(readouts['refits']) == {'B', 'R'} and
          isinstance(blind, dict) and set(blind) == {'0', 'B', 'R'}, 'Joint group schema')
  analysis = result['analysis'] if 'analysis' in result else result
  frozen = readouts['frozen']
  compare = Comparison()
  compare.same(frozen['version'], 'DL-reset-readout-r1', 'freeze.version')
  compare.same(analysis['version'], 'DL-reset-readout-r1', 'analysis.version')
  compare.same(frozen['blind_seen'], False, 'freeze.blind_seen')
  compare.same(frozen['lambda_grid'], list(LAMBDAS), 'freeze.lambda_grid')
  compare.same(frozen['signal_primary_model'], '0', 'freeze.signal_primary')
  fits = {'0': frozen['fit'], **readouts['refits']}
  for name in ('0', 'B', 'R'):
    validate_batch(readouts['cal'][name], 8, 'cal.' + name)
    validate_batch(blind[name], 24, 'blind.' + name)
    compare.same(readouts['cal'][name]['episode_ids'], readouts['cal']['0']['episode_ids'], 'cal.ids.' + name)
    compare.same(readouts['cal'][name]['returns'], readouts['cal']['0']['returns'], 'cal.Y.' + name)
    compare.same(blind[name]['episode_ids'], blind['0']['episode_ids'], 'blind.ids.' + name)
    compare.same(blind[name]['returns'], blind['0']['returns'], 'blind.Y.' + name)
    for key, value in blind[name].items():
      compare.same(analysis['input_digests'][name][key], digest(value),
                   'input_digest.' + name + '.' + key)
    # Verify the declared common-history / prior-sample object in the actual
    # promoted numeric inputs too; original BF16/logits need the model audit.
    common_h = readouts['cal'][name]['h'][0].tobytes()
    common_p = readouts['cal'][name]['zp'][0].tobytes()
    require(all(row.tobytes() == common_h for batch in
        (readouts['cal'][name], blind[name]) for row in batch['h']),
        'Cross-phase common h differs: ' + name)
    require(all(row.tobytes() == common_p for batch in
        (readouts['cal'][name], blind[name]) for row in batch['zp']),
        'Cross-phase common p sample differs: ' + name)
  require(set(blind['0']['episode_ids'].tolist()).isdisjoint(CAL) and
          set(blind['0']['episode_ids'].tolist()) | set(CAL) == set(range(32)), 'Complete split differs')
  cal = readouts['cal']['0']
  loeo = {rule: np.empty((8, 2, 7), np.float64) for rule in LAMBDAS}
  recorded_loeo = {rule: np.empty((8, 2, 7), np.float64) for rule in LAMBDAS}
  require(len(frozen['fold_metadata']) == 8, 'Complete eight-fold metadata required')
  for e in range(8):
    train = np.array([i for i in range(8) if i != e])
    held = {key: value[[e]] for key, value in cal.items()}
    fold = frozen['fold_metadata'][e]
    compare.same(fold['heldout_episode'], int(cal['episode_ids'][e]), 'fold.heldout')
    compare.same(fold['training_episodes'], cal['episode_ids'][train].tolist(), 'fold.train')
    require(len(fold['candidates']) == 4, 'Complete fold lambda grid required')
    for j, rule in enumerate(LAMBDAS):
      head = direct_shared(cal, train, rule)
      pred, samples = predict(head, held)
      dec = decisions(pred, held['returns'])
      loeo[rule][e] = pred[0]
      stored = fold['candidates'][j]
      path = f'fold.{e}.lambda.{rule}'
      compare.same(stored['lambda_value'], rule, path + '.lambda')
      compare.close(stored['mean_prediction'], pred[0], path + '.prediction')
      compare.close(stored['sample_predictions'], samples[0], path + '.sample_predictions')
      actual_mean = np.asarray(stored['sample_predictions'], np.float64).mean(1, dtype=np.float64)
      compare.same(stored['mean_prediction'], actual_mean, path + '.recorded_mean4')
      recorded_loeo[rule][e] = actual_mean
      compare.same(stored['choices'], dec['choices'][0], path + '.choice')
      compare.close(stored['pooled_utility'], mean([dec['q'][0], dec['p'][0]]), path + '.utility')
      compare.close(stored['pooled_mse'], mean(np.square(pred - center(held['returns'])[:, None])), path + '.mse')
      verify_fold_metadata(stored['fit_metadata'], head, compare, path + '.fit')
  candidates = []
  for j, rule in enumerate(LAMBDAS):
    dec = decisions(loeo[rule], cal['returns'])
    row = dict(**{'lambda': rule}, pooled_utility=mean(np.column_stack((dec['q'], dec['p']))),
               pooled_mse=mean(np.square(loeo[rule] - center(cal['returns'])[:, None])))
    candidates.append(row)
    stored = frozen['candidates'][j]
    for key in ('lambda', 'pooled_utility', 'pooled_mse'):
      compare.close(stored[key], row[key], 'candidate.' + str(rule) + '.' + key)
    compare.close(stored['oof_mean_prediction'], loeo[rule], 'candidate.oof.' + str(rule))
  rule, u_ties, mse_ties = select_lambda(candidates)
  compare.same(frozen['selected_lambda'], rule, 'selected_lambda')
  compare.same(frozen['selection']['selected_lambda'], rule, 'selection.lambda')
  compare.same(frozen['selection']['utility_tie_candidates'], u_ties, 'selection.utility_ties')
  compare.same(frozen['selection']['mse_tie_candidates'], mse_ties, 'selection.mse_ties')
  oof = decisions(loeo[rule], cal['returns'])
  actual_oof = decisions(recorded_loeo[rule], cal['returns'])
  for key, expected in (('prediction', loeo[rule]), ('S', oof['S']), ('U', oof['U'])):
    compare.close(frozen['oof'][key], expected, 'oof.' + key)
  compare.same(frozen['oof']['choices'], oof['choices'], 'oof.choices')
  compare.same(frozen['oof']['prediction'], recorded_loeo[rule], 'oof.recorded_predictions')
  compare.same(frozen['oof']['choices'], actual_oof['choices'], 'oof.recorded_choices')
  compare.same(np.asarray(frozen['oof']['S'], np.float64), actual_oof['S'], 'oof.recorded_S')
  compare.same(np.asarray(frozen['oof']['U'], np.float64), actual_oof['U'], 'oof.recorded_U')
  threshold = float(np.median(cal['D']))
  compare.same(frozen['high_D_threshold'], threshold, 'high_D_threshold')
  compare.same(analysis['baseline_lambda_reused_for_B_R'], rule, 'analysis.shared_lambda')
  signals = {}
  for name in SIGNALS:
    # This source S has just been independently verified against direct F.
    # Use its actual recorded floating values for the declared downstream fit.
    verified_cal_S = actual_oof['S']
    signals[name] = direct_signal(slot_values(name, cal['D'], cal['K'], verified_cal_S), oof['U'])
    fit, expected = frozen['regressors'][name], signals[name]
    for key in ('mean', 'rms', 'weights', 'intercept', 'effective_df', 'training_predictions'):
      compare.close(fit[key], expected[key], 'signal.fit.' + name + '.' + key)
    compare.same(fit['lambda_value'], 1., 'signal.lambda.' + name)
    compare.same(fit['nominal_slots'], 2, 'signal.slots.' + name)
    compare.same(fit['constant_target'], expected['constant_target'], 'signal.constant.' + name)
    compare.same(fit['rank_defaulttol'], expected['rank'], 'signal.rank.' + name)
  indices = np.random.Generator(np.random.PCG64(SEED)).integers(0, 24, (2000, 24))
  compare.same(analysis['statistics']['seed'], SEED, 'statistics.seed')
  compare.same(analysis['statistics']['bootstrap_draws'], 2000, 'statistics.draws')
  compare.same(analysis['statistics']['episode_count'], 24, 'statistics.episodes')
  compare.same(analysis['statistics']['bootstrap_indices_digest'], digest(indices), 'statistics.indices')
  model_values, model_decisions, failures = {}, {}, {}
  for name in ('0', 'B', 'R'):
    model_cal = readouts['cal'][name]
    head = direct_shared(model_cal, np.arange(8), rule)
    verify_fit(fits[name]['model'], head, compare, name + '.fit')
    compare.same(fits[name]['lambda_value'], rule, name + '.lambda')
    compare.same(fits[name]['episode_ids'], model_cal['episode_ids'].tolist(), name + '.cal_episode_ids')
    compare.same(fits[name]['returns_digest'], digest(model_cal['returns']), name + '.cal_returns')
    constant_values = model_cal['returns'].mean(0, dtype=np.float64)
    const = int(np.argmax(constant_values))
    compare.close(fits[name]['constant_values'], constant_values, name + '.constant_values')
    compare.same(fits[name]['constant_choice'], const, name + '.constant_choice')
    pred, samples = predict(head, blind[name])
    direct_dec = decisions(pred, blind[name]['returns'])
    stored = analysis['models'][name]
    compare.close(stored['predictions'], pred, name + '.predictions')
    compare.close(stored['sample_predictions'], samples, name + '.sample_predictions')
    compare.same(stored['choices'], direct_dec['choices'], name + '.choices')
    compare.close(stored['S_decision'], direct_dec['S'], name + '.S')
    compare.close(stored['true_U'], direct_dec['U'], name + '.U')
    # Recover statistics from the producer's authenticated actual F measurements,
    # not a numerically nearby alternate solver realization. The values above
    # have all passed the independent direct-fit oracle; choice remains exact.
    recorded_samples = np.asarray(stored['sample_predictions'], np.float64)
    recorded_prediction = recorded_samples.mean(axis=2, dtype=np.float64)
    compare.same(stored['predictions'], recorded_prediction, name + '.recorded_mean4')
    dec = decisions(recorded_prediction, blind[name]['returns'])
    compare.same(stored['choices'], dec['choices'], name + '.recorded_choices')
    compare.same(np.asarray(stored['S_decision'], np.float64), dec['S'], name + '.recorded_S')
    model_decisions[name] = dec
    Y = blind[name]['returns']
    constant_reward = Y[:, const]
    centered = center(Y)
    # NumPy control mean is the declared per-episode measurement. Separately
    # verify it against fsum; the bootstrap of those measured points uses fsum.
    mse_q = np.square(recorded_prediction[:, 0] - centered).mean(1, dtype=np.float64)
    mse_p = np.square(recorded_prediction[:, 1] - centered).mean(1, dtype=np.float64)
    for branch, measured in ((0, mse_q), (1, mse_p)):
      fsum_mse = np.array([mean((recorded_prediction[i, branch] - centered[i]) ** 2)
                          for i in range(24)])
      compare.close(measured, fsum_mse, name + '.fsum_MSE.' + str(branch))
    values = dict(q_absolute=dec['q'], p_absolute=dec['p'], constant_absolute=constant_reward,
        q_minus_p=dec['U'], q_minus_constant=dec['q'] - constant_reward,
        q_centered_mse=mse_q, p_centered_mse=mse_p,
        q_regret=Y.max(axis=1) - dec['q'], p_regret=Y.max(axis=1) - dec['p'])
    model_values[name] = values
    for key, value in values.items():
      verify_summary(stored['metrics'][key], summary(value, indices), compare, name + '.' + key)
